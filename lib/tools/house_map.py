"""Build a house's whole-house map data from its house_layout.py.

Usage: python3 lib/tools/house_map.py houses/<house>

Writes houses/<house>/web/house.js (window.HOUSE = {...}), which web/index.html and
lib/web/housemap.js draw as a floor-by-floor plan and a 3D dollhouse. A room with a folder
under rooms/ gets its status line from its README and links to its walkthrough, plans and
selections; every other room is a placeholder.
"""
import importlib.util
import json
import os
import re
import sys

# rooms' layout.py files import roomkit from lib/
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
house = os.path.abspath(sys.argv[1])
spec = importlib.util.spec_from_file_location("house_layout", os.path.join(house, "house_layout.py"))
L = importlib.util.module_from_spec(spec)
spec.loader.exec_module(L)


def area_sqft(pts):
    a = sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]))
    return round(abs(a) / 2 / 144)


def room_status(folder):
    readme = os.path.join(house, "rooms", folder, "README.md")
    if os.path.exists(readme):
        m = re.search(r"status:\s*(.+)", open(readme).read())
        if m:
            return m.group(1).strip()
    return "modeled"


def links(folder):
    web = os.path.join(house, "rooms", folder, "web")
    out = []
    for page, label in (("index.html", "Walkthrough"), ("plans.html", "Plans"), ("selections.html", "Selections")):
        if os.path.exists(os.path.join(web, page)):
            out.append([label, f"../rooms/{folder}/web/{page}"])
    return out


rooms = []
for r in L.ROOMS:
    pts = [[float(x), float(y)] for x, y in r["outline"]]
    folder = r.get("folder")
    if folder and not os.path.isdir(os.path.join(house, "rooms", folder)):
        sys.exit(f"{r['id']}: rooms/{folder} doesn't exist")
    rooms.append(dict(
        id=r["id"], name=r["name"], floor=r["floor"], kind=r.get("kind", "room"),
        listed=r.get("listed"), area=area_sqft(pts), outline=pts,
        source=r.get("source", "FROM PLAN"), note=r.get("note"), to=r.get("to"),
        folder=folder, status=room_status(folder) if folder else "placeholder",
        links=links(folder) if folder else [], seen_in=r.get("seen_in"),
    ))

ids = {r["id"] for r in rooms}
for r in rooms:
    for k in ("to", "seen_in"):
        if r[k] and r[k] not in ids and not os.path.isdir(os.path.join(house, "rooms", r[k])):
            sys.exit(f"{r['id']}: {k} {r[k]!r} isn't a room")

# where each listing plan sits in house inches (svg <image> box, y down = -north)
plans = {}
for floor, p in L.PLANS.items():
    w, h = p["size_px"]
    x0 = (p["shift_px"] - L.ORIGIN_PX[0]) / L.PX_PER_IN
    y0 = -L.ORIGIN_PX[1] / L.PX_PER_IN
    plans[floor] = dict(href="../" + p["image"], x=round(x0, 1), y=round(y0, 1),
                        w=round(w / L.PX_PER_IN, 1), h=round(h / L.PX_PER_IN, 1))

data = dict(units="inches; x east, y north, z up; origin at one room's interior NW corner (house_layout.py)",
            floors=L.FLOORS, rooms=rooms, plans=plans,
            wall=L.WALL_T, ext_wall=L.EXT_WALL_T)
os.makedirs(os.path.join(house, "web"), exist_ok=True)
out = os.path.join(house, "web", "house.js")
with open(out, "w") as f:
    f.write("// generated by lib/tools/house_map.py from house_layout.py; edit that, then re-run\n")
    f.write("window.HOUSE = " + json.dumps(data, indent=1) + ";\n")
print(f"wrote {os.path.relpath(out)}: {len(rooms)} rooms, "
      f"{sum(1 for r in rooms if r['folder'])} modeled")
