"""Write a room's web/selections.html: selections.md as a styled page with the site's nav bar.
Usage: python3 lib/tools/selections_page.py houses/<house>/rooms/<room>
Re-run after editing selections.md. The Markdown is embedded in the page (so it also opens
straight from disk) and drawn by marked.js; relative links point back into the room folder."""
import html
import json
import os
import sys

room = os.path.abspath(sys.argv[1])
house = os.path.dirname(os.path.dirname(room))


def title(path, fallback):
    try:
        with open(path) as f:
            for line in f:
                if line.startswith("# "):
                    return line[2:].strip()
    except FileNotFoundError:
        pass
    return fallback


room_name = title(os.path.join(room, "README.md"), os.path.basename(room))
house_name = title(os.path.join(house, "house.md"), os.path.basename(house))
md = open(os.path.join(room, "selections.md")).read()
up = "../../../../../"     # web/ -> repo root
# the house name links to the whole-house map once the house has one
house_crumb = html.escape(house_name)
if os.path.exists(os.path.join(house, "web", "index.html")):
    house_crumb = f'<a href="../../../web/index.html#{os.path.basename(room)}">{house_crumb}</a>'

page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(room_name)} Selections</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,500;12..96,700&family=Instrument+Sans:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="{up}lib/web/walkthrough.css">
<link rel="stylesheet" href="{up}lib/web/page.css">
</head>
<body class="doc">
<!-- generated by lib/tools/selections_page.py from selections.md; edit that, then re-run -->
<header>
  <nav class="crumbs" aria-label="Breadcrumb">
    <a href="{up}index.html">All rooms</a><span>/</span>{house_crumb}<span>/</span><b>{html.escape(room_name)}</b>
  </nav>
  <div class="tabs">
    <a href="index.html">Walk through</a>
    <a href="plans.html">Plans</a>
    <a href="selections.html" aria-current="page">Selections</a>
  </div>
</header>
<main><article id="doc"></article></main>
<script src="https://cdn.jsdelivr.net/npm/marked@12.0.2/marked.min.js"></script>
<script src="{up}lib/web/lightbox.js"></script>
<script>
const MD = {json.dumps(md)};
const slug = (t) => t.toLowerCase().replace(/<[^>]+>/g, "").replace(/[^a-z0-9 -]/g, "").trim().replace(/ +/g, "-");
marked.use({{
  // links and images inside the room folder are written relative to it; this page sits in web/
  walkTokens(t) {{
    if ((t.type === "link" || t.type === "image") && !/^([a-z]+:|#|\\/)/i.test(t.href)) t.href = "../" + t.href;
  }},
  renderer: {{
    heading(text, level) {{ return `<h${{level}} id="${{slug(text)}}">${{text}}</h${{level}}>`; }},
    link(href, title, text) {{
      const ext = /^https?:/.test(href) ? ' target="_blank" rel="noopener"' : "";
      return `<a href="${{href}}"${{ext}}>${{text}}</a>`;
    }},
  }},
}});
document.getElementById("doc").innerHTML = marked.parse(MD);
// pictures open larger in a popup
Lightbox.attach("#doc img");
// status words read as tags
document.querySelectorAll("#doc p strong, #doc li strong").forEach((s) => {{
  if (s.textContent === "Status:") s.parentElement.classList.add("status");
}});
</script>
</body>
</html>
"""
out = os.path.join(room, "web", "selections.html")
with open(out, "w") as f:
    f.write(page)
print(out)
